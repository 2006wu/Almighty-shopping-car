"""Generate the C subset from the canonical YAML contract and xacro geometry."""
import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
import yaml


def render(interface, xacro):
    spec = yaml.safe_load(Path(interface).read_text())
    props = {e.get('name'): e.get('value') for e in ET.parse(xacro).getroot()
             if e.tag.endswith('}property')}
    radius = float(props['wheel_radius'])
    track = (float(props['width'])-float(props['wheel_width']))*float(props['skid_track_factor'])
    lines = ['/* Generated by generate_contract.py; do not edit. */', '#pragma once']
    for group in ('timing', 'model'):
        for key, value in spec[group].items():
            lines.append(f'#define MCU_{key.upper()} {value}')
    for status in spec['status_values']:
        lines.append(f'#define MCU_STATUS_{status} "{status}"')
    for key in ('cmd', 'wheel', 'mcu_heartbeat', 'pc_heartbeat', 'status', 'drop_commands'):
        topic = spec['topics'][key]
        lines += [f'#define MCU_{key.upper()}_TOPIC "{topic["name"]}"',
                  f'#define MCU_{key.upper()}_RATE {topic["rate"]}',
                  f'#define MCU_{key.upper()}_DEPTH {topic["depth"]}']
    lines += [f'#define MCU_WHEEL_RADIUS {radius}', f'#define MCU_TRACK {track:.12g}',
              '#define MCU_WHEEL_FRAME "'+spec['topics']['wheel']['frame']+'"',
              '#define MCU_WHEEL_NAMES {'+', '.join('"'+n+'"' for n in spec['wheel_names'])+'}']
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('interface')
    parser.add_argument('xacro')
    parser.add_argument('output')
    args = parser.parse_args()
    Path(args.output).write_text(render(args.interface, args.xacro))
